export const catalogs: Record<Locale, Readonly<Partial<Catalog>>> = {
  en,
  "zh-CN": zhCN,
};

export function resolveLocale(
  preference: LanguagePreference,
  languages: readonly string[] = browserLanguages(),
): Locale {
  if (preference !== "system") return preference;
  const normalized = languages.map((language) => language.toLowerCase());
  for (const language of normalized) {
    if (
      language === "zh" ||
      language.startsWith("zh-cn") ||
      language.startsWith("zh-sg") ||
      language.startsWith("zh-hans")
    ) {
      return "zh-CN";
    }
    if (language === "en" || language.startsWith("en-")) return "en";
  }
  return "en";
}

function browserLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return ["en"];
  return navigator.languages?.length ? navigator.languages : [navigator.language];
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
  source: Record<Locale, Readonly<Partial<Catalog>>> = catalogs,
): string {
  const template = source[locale]?.[key] ?? source.en?.[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

export function translator(locale: Locale) {
  return (key: TranslationKey, values?: Record<string, string | number>) =>
    translate(locale, key, values);
}

export function missingTranslationKeys(locale: Locale): TranslationKey[] {
  return (Object.keys(en) as TranslationKey[]).filter(
    (key) => catalogs[locale][key] === undefined,
  );
}
